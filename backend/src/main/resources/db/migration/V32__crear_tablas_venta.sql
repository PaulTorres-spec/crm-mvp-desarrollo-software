-- V32: ventas y su detalle (RF05 - CU08 Registrar venta, CU09 Asociar venta a cliente)

-- Correlativo del número de venta (V-AAAA-NNNN); seguro con usuarios simultáneos
CREATE SEQUENCE venta_correlativo_seq START WITH 1;

CREATE TABLE venta (
    id                BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    numero            VARCHAR(15)   NOT NULL,
    cliente_id        BIGINT        NOT NULL,
    fecha             DATE          NOT NULL,
    observaciones     VARCHAR(300),
    subtotal          NUMERIC(12,2) NOT NULL,
    igv               NUMERIC(12,2) NOT NULL,
    total             NUMERIC(12,2) NOT NULL,
    registrado_por_id BIGINT        NOT NULL,
    fecha_registro    TIMESTAMP     NOT NULL DEFAULT now(),

    CONSTRAINT pk_venta                PRIMARY KEY (id),
    CONSTRAINT uk_venta_numero         UNIQUE (numero),
    CONSTRAINT fk_venta_cliente        FOREIGN KEY (cliente_id) REFERENCES cliente (id),
    CONSTRAINT fk_venta_registrado_por FOREIGN KEY (registrado_por_id) REFERENCES usuario (id),
    CONSTRAINT ck_venta_montos         CHECK (subtotal >= 0 AND igv >= 0 AND total = subtotal + igv)
);

CREATE TABLE detalle_venta (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    venta_id        BIGINT        NOT NULL,
    producto_id     BIGINT        NOT NULL,
    cantidad        NUMERIC(10,2) NOT NULL,
    precio_unitario NUMERIC(10,2) NOT NULL,
    subtotal        NUMERIC(12,2) NOT NULL,

    CONSTRAINT pk_detalle_venta          PRIMARY KEY (id),
    CONSTRAINT uk_detalle_venta_producto UNIQUE (venta_id, producto_id),
    CONSTRAINT fk_detalle_venta_venta    FOREIGN KEY (venta_id) REFERENCES venta (id) ON DELETE CASCADE,
    CONSTRAINT fk_detalle_venta_producto FOREIGN KEY (producto_id) REFERENCES producto (id),
    CONSTRAINT ck_detalle_venta_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_detalle_venta_precio   CHECK (precio_unitario > 0),
    CONSTRAINT ck_detalle_venta_subtotal CHECK (subtotal = ROUND(cantidad * precio_unitario, 2))
);

-- Índices para los filtros de CU10/CU11 y para las FK (PostgreSQL no los crea solo)
CREATE INDEX idx_venta_cliente          ON venta (cliente_id);
CREATE INDEX idx_venta_fecha            ON venta (fecha);
CREATE INDEX idx_venta_registrado_por   ON venta (registrado_por_id);
CREATE INDEX idx_detalle_venta_producto ON detalle_venta (producto_id);