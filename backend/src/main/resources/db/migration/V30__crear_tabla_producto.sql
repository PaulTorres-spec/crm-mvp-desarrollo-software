-- V30: catálogo de productos (RF05 - CU08 Registrar venta)
CREATE TABLE producto (
    id                 BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    codigo             VARCHAR(20)   NOT NULL,
    nombre             VARCHAR(120)  NOT NULL,
    unidad_medida      VARCHAR(10)   NOT NULL DEFAULT 'KG',
    precio_referencial NUMERIC(10,2) NOT NULL,
    activo             BOOLEAN       NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_producto                    PRIMARY KEY (id),
    CONSTRAINT uk_producto_codigo             UNIQUE (codigo),
    CONSTRAINT uk_producto_nombre             UNIQUE (nombre),
    CONSTRAINT ck_producto_precio_referencial CHECK (precio_referencial > 0)
);